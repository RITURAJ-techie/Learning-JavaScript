const month = 3

switch (month) {
    case 1:
        console.log("January")
        break;
    case 2:
        console.log("Febuary")
        break;
    case 3:
        console.log("March")
        break;
    case 4:
        console.log("April")
        break;

    default:
        console.log("Nothing Matched")
        break;
}

// If any switch statement matches the condition,
// after that switch executes all the statements.,
// that's why Break is Imp.